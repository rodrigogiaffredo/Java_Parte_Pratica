public class Gb02Variaveis {

    public static void main(String[] args) {
        
        /** 
         * Sintaxe de declaração de varíavel em Java: 
         * com valor: <tipo> identificador = valor;
         * sem valor: <tipo: identificador;
         * 
         * Variável declarada LOCALMENTE dentro de bloco de comandos da função 'main'.
         */
        String saudacao = "Como vai você?";

        /**
         * Chamada da variável: é feita através de seu identificador
         */
        System.out.println("Olá! " + saudacao);
    }    
}
